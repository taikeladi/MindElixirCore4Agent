test('restoring a stale draft keeps its old base revision across a second reload', async ({ page, request }) => {
  await page.goto('/')
  await expect(page.locator('[data-nodeid="meb"]')).toBeVisible()
  await page.route('**/api/document', route => route.request().method() === 'POST' ? route.abort() : route.continue())
  await page.locator('[data-nodeid="meb"]').dblclick({ delay: 70 })
  await page.locator('#input-box').fill('旧版本草稿')
  await page.locator('#input-box').press('Enter')
  await expect(page.locator('#notice')).toContainText('暂时不可用')
  await edit(request, [{ type: 'update_node', id: 'b', patch: { topic: '必须保留的最新版本' } }])
  page.on('dialog', dialog => dialog.accept())
  await page.reload()
  await page.unroute('**/api/document')
  await page.locator('#restore-draft').click()
  await expect(page.locator('#notice')).toContainText('草稿基于旧版本')
  await page.reload()
  await page.locator('#restore-draft').click()
  await expect(page.locator('#notice')).toContainText('草稿基于旧版本')
  expect((await get(request)).data.nodeData.children[1].topic).toBe('必须保留的最新版本')
})

test('sample document: human note, AI supplement, reload, provenance and viewport fit', async ({ page, request }) => {
  const sample = JSON.parse(await readFile(resolve(import.meta.dirname, '../examples/城市绿地观察计划.mindmap.json'), 'utf8'))
  const doc = await get(request)
  expect((await request.post('/api/document', { data: { documentId: doc.documentId, baseRevision: doc.revision, requestId: randomUUID(), data: sample } })).ok()).toBeTruthy()
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto('/')
  await page.locator('[data-nodeid="meexample-method"]').click()
  await page.locator('#details-toggle').click()
  await page.locator('#node-note').fill('人工阅读笔记：每次记录观察时段和天气。')
  await page.getByRole('button', { name: '保存节点详情' }).click()
  await expect(page.locator('#save-status')).toHaveText('已保存到本机')
  await page.locator('#details-close').click()
  await edit(request, [{ type: 'add_node', parentId: 'example-limits', node: { id: 'example-question', topic: '待验证：增加季节覆盖', metadata: { kind: 'inference', sources: [{ document: '城市绿地观察计划.md', section: '5. 局限', quote: '天气、临时活动以及有限的观察时段都可能影响记录。' }] }, note: '由局限提出的后续研究问题，原文未承诺实施。' } }])
  await expect(page.locator('[data-nodeid="meexample-question"]')).toBeVisible()
  await page.reload()
  await expect(page.locator('[data-nodeid="meexample-question"]')).toBeVisible()
  const latest = await get(request)
  expect(latest.data.nodeData.children[1].note).toContain('人工阅读笔记')
  expect(latest.data.nodeData.children[1].metadata.sources[0].section).toBe('2. 观察方法')
  const bounds = await page.locator('me-tpc').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().toJSON()))
  for (const rect of bounds) {
    expect(rect.top).toBeGreaterThanOrEqual(72)
    expect(rect.bottom).toBeLessThanOrEqual(920)
    expect(rect.left).toBeGreaterThanOrEqual(0)
    expect(rect.right).toBeLessThanOrEqual(1440)
  }
  const artifactDirectory = resolve(import.meta.dirname, '../artifacts')
  await mkdir(artifactDirectory, { recursive: true })
  await page.screenshot({ path: resolve(artifactDirectory, 'example-preview.png') })
})
